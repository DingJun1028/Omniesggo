import { NextResponse } from 'next/server';
import { PrismaClient, createPrismaCompatClient } from '@lib/db/prisma-compat';
import { jsPDF } from 'jspdf';

const prisma = createPrismaCompatClient();

export async function GET(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;

    const record = await prisma.netZeroRoadmap.findUnique({
      where: { id },
    });

    if (!record) {
      return NextResponse.json({ success: false, error: '找不到該筆 5T 淨零路徑規劃紀錄' }, { status: 404 });
    }

    const measures = JSON.parse(record.measuresJson || '[]');
    const totalPlannedReduction = measures.reduce((acc: number, m: any) => acc + (m.reductionPotential || 0), 0);
    const target2030Emissions = record.baseEmissions * (1 - record.target2030Percent / 100);

    // Initialize A4 PDF
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

    // Header & Banner
    doc.setFillColor(2, 6, 23);
    doc.rect(0, 0, 210, 45, 'F');

    doc.setTextColor(6, 182, 212);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('NET-ZERO ROADMAP CERTIFICATE', 15, 20);

    doc.setTextColor(248, 250, 252);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text('SBTi 1.5°C Abatement Pathway Audit Report', 15, 28);

    doc.setTextColor(16, 185, 129);
    doc.setFontSize(10);
    doc.text(`Hash Lock: ${record.hashLock.slice(0, 32)}...`, 15, 36);

    // Metadata & Summary
    doc.setTextColor(15, 23, 42);
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Path Targets Summary', 15, 55);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Base Year: ${record.baseYear}`, 15, 63);
    doc.text(`Base Emissions: ${record.baseEmissions.toLocaleString()} tCO2e/yr`, 15, 70);
    doc.text(`2030 SBTi Reduction Target: ${record.target2030Percent}% (Target: ${target2030Emissions.toLocaleString()} tCO2e/yr)`, 15, 77);
    doc.text(`Total Abatement Capacity: ${totalPlannedReduction.toLocaleString()} tCO2e/yr`, 15, 84);

    // 5T Seals
    doc.setFillColor(241, 245, 249);
    doc.rect(15, 92, 180, 35, 'F');
    doc.setFont('helvetica', 'bold');
    doc.text('5T Protocol Verification Seals:', 20, 100);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('• [Truth] Source Origin: omni-roadmap (SBTi 1.5C Criteria)', 20, 107);
    doc.text('• [Goodness] ISO-14064-1 & MACC Abatement Cost Model Verified', 20, 113);
    doc.text('• [Trust] Cryptographic Hash Lock: SHA-256 Verified', 20, 119);
    doc.text('• [Trackable] Sealed Timestamp: ' + new Date(record.createdAt).toISOString(), 20, 125);

    // Measures Table
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text(`Planned Decarbonization Measures (${measures.length} Actions)`, 15, 138);

    let y = 146;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setFillColor(226, 232, 240);
    doc.rect(15, y - 5, 180, 8, 'F');
    doc.text('Measure Name', 18, y);
    doc.text('Category', 85, y);
    doc.text('Reduction (tCO2e)', 125, y);
    doc.text('MACC ($/tCO2e)', 160, y);

    y += 8;
    doc.setFont('helvetica', 'normal');

    measures.slice(0, 12).forEach((m: any) => {
      if (y > 270) return;
      doc.text(String(m.name || 'Unnamed Measure').slice(0, 30), 18, y);
      doc.text(String(m.category || 'Efficiency'), 85, y);
      doc.text(`${Number(m.reductionPotential || 0).toLocaleString()}`, 125, y);
      doc.text(`$${Number(m.costPerTon || 0).toFixed(0)}`, 160, y);
      y += 7;
    });

    // Footer Stamp
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text('Official Cryptographic Certificate generated by ESG GO OmniAgent Swarm Engine v2.9.0', 15, 285);

    const pdfArrayBuffer = doc.output('arraybuffer');

    return new Response(pdfArrayBuffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="5T_NetZero_Roadmap_Certificate_${record.id.slice(0, 8)}.pdf"`,
      },
    });
  } catch (error) {
    console.error('[roadmap/export-pdf]', error);
    return NextResponse.json(
      { success: false, error: (error as Error).message },
      { status: 500 }
    );
  }
}
