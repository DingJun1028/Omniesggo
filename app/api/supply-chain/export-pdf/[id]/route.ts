import { NextResponse } from 'next/server';
import { PrismaClient, createPrismaCompatClient } from '@lib/db/prisma-compat';
import { jsPDF } from 'jspdf';

const prisma = createPrismaCompatClient();

export async function GET(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;

    const vendor = await prisma.supplyChainVendor.findUnique({
      where: { id },
    });

    if (!vendor) {
      return NextResponse.json({ success: false, error: '找不到該筆 5T 供應鏈 CSDD 稽核紀錄' }, { status: 404 });
    }

    const strengths = JSON.parse(vendor.strengthsJson || '[]');
    const weaknesses = JSON.parse(vendor.weaknessesJson || '[]');

    // Initialize A4 PDF
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

    // Header Banner
    doc.setFillColor(2, 6, 23);
    doc.rect(0, 0, 210, 45, 'F');

    doc.setTextColor(6, 182, 212);
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('SUPPLY CHAIN CSDD AUDIT CERTIFICATE', 15, 20);

    doc.setTextColor(248, 250, 252);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text('EU Corporate Sustainability Due Diligence Audit Report', 15, 28);

    doc.setTextColor(16, 185, 129);
    doc.setFontSize(10);
    doc.text(`Hash Lock: ${vendor.hashLock.slice(0, 32)}...`, 15, 36);

    // Vendor Overview
    doc.setTextColor(15, 23, 42);
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Supplier Audit Rating Summary', 15, 55);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Supplier Name: ${vendor.supplierName}`, 15, 63);
    doc.text(`Industry / Tier: ${vendor.industry} (${vendor.tier})`, 15, 70);
    doc.text(`ESG Overall Rating: Class ${vendor.rating} (Risk Level: ${vendor.riskLevel})`, 15, 77);

    // Scores Grid
    doc.setFillColor(241, 245, 249);
    doc.rect(15, 85, 180, 25, 'F');
    doc.setFont('helvetica', 'bold');
    doc.text('ESG Dimension Performance Scores:', 20, 93);
    doc.setFont('helvetica', 'normal');
    doc.text(`Environmental (E): ${vendor.envScore} / 100`, 20, 102);
    doc.text(`Social (S): ${vendor.socialScore} / 100`, 80, 102);
    doc.text(`Governance (G): ${vendor.govScore} / 100`, 140, 102);

    // 5T Verification Box
    doc.setFillColor(248, 250, 252);
    doc.rect(15, 118, 180, 30, 'F');
    doc.setFont('helvetica', 'bold');
    doc.text('5T Protocol Verification Seals:', 20, 125);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('• [Truth] Source Origin: omni-supply-chain (EU CSDD Directive Compliant)', 20, 131);
    doc.text('• [Goodness] ISO-20400 & EcoVadis Equivalent Scoring Engine', 20, 137);
    doc.text('• [Trust] SHA-256 Hash Lock Imprint: Verified', 20, 143);

    // Audit Findings & Recommendations
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Audit Strengths & Key Findings:', 15, 158);

    let y = 166;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    strengths.slice(0, 4).forEach((s: string) => {
      doc.text(`✓ ${s}`, 20, y);
      y += 6;
    });

    y += 4;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Risk Gaps & Improvement Actions:', 15, y);
    y += 8;

    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    weaknesses.slice(0, 4).forEach((w: string) => {
      doc.text(`⚠ ${w}`, 20, y);
      y += 6;
    });

    y += 6;
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Governance Recommendation:', 15, y);
    y += 8;

    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.text(vendor.recommendation || 'Maintain active ESG monitoring.', 20, y);

    // Footer
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text('Official Cryptographic Certificate generated by ESG GO OmniAgent Swarm Engine v2.9.0', 15, 285);

    const pdfArrayBuffer = doc.output('arraybuffer');

    return new Response(pdfArrayBuffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="5T_SupplyChain_CSDD_Certificate_${vendor.id.slice(0, 8)}.pdf"`,
      },
    });
  } catch (error) {
    console.error('[supply-chain/export-pdf]', error);
    return NextResponse.json(
      { success: false, error: (error as Error).message },
      { status: 500 }
    );
  }
}
