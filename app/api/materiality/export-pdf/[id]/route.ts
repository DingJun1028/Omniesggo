import { NextResponse } from 'next/server';
import { PrismaClient, createPrismaCompatClient } from '@lib/db/prisma-compat';
import { jsPDF } from 'jspdf';

const prisma = createPrismaCompatClient();

export async function GET(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;

    const record = await prisma.materialityAssessment.findUnique({
      where: { id },
    });

    if (!record) {
      return NextResponse.json({ success: false, error: '找不到該筆 5T 雙重重大性評估紀錄' }, { status: 404 });
    }

    const topics = JSON.parse(record.topicsJson || '[]');

    // Initialize A4 PDF
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

    // Header & Title
    doc.setFillColor(2, 6, 23); // dark void background for header banner
    doc.rect(0, 0, 210, 45, 'F');

    doc.setTextColor(6, 182, 212); // cyan core
    doc.setFontSize(22);
    doc.setFont('helvetica', 'bold');
    doc.text('ESG GO 5T AUDIT CERTIFICATE', 15, 20);

    doc.setTextColor(248, 250, 252);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text('Double Materiality Assessment (GRI & CSRD ESRS Compliant)', 15, 28);

    doc.setTextColor(16, 185, 129); // emerald soul
    doc.setFontSize(10);
    doc.text(`Hash Lock: ${record.hashLock.slice(0, 32)}...`, 15, 36);

    // Body Metadata
    doc.setTextColor(15, 23, 42);
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text('Assessment Metadata', 15, 55);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Certificate ID: ${record.id}`, 15, 63);
    doc.text(`Target Year: ${record.year}`, 15, 70);
    doc.text(`Source Origin: ${record.sourceOrigin}`, 15, 77);
    doc.text(`Issued At: ${new Date(record.createdAt).toISOString()}`, 15, 84);

    // 5T Protocol Safeguard Status
    doc.setFillColor(241, 245, 249);
    doc.rect(15, 92, 180, 35, 'F');
    doc.setFont('helvetica', 'bold');
    doc.text('5T Protocol Verification Seals:', 20, 100);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.text('• [Truth] Origin Verified: source_origin = omni-materiality', 20, 107);
    doc.text('• [Goodness] Formula: GRI 3-3 & CSRD ESRS E1-G1 Matrix Algorithm', 20, 113);
    doc.text('• [Trust] Cryptographic Hash Lock: SHA-256 Verified', 20, 119);
    doc.text('• [Trackable] Lifecycle Path: Supabase PostgreSQL Vault Sealed', 20, 125);

    // Materiality Matrix Table
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text(`Assessed Material Topics (${topics.length} Key Issues)`, 15, 138);

    let y = 146;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    doc.setFillColor(226, 232, 240);
    doc.rect(15, y - 5, 180, 8, 'F');
    doc.text('Topic Name', 18, y);
    doc.text('Financial Imp.', 90, y);
    doc.text('Impact Imp.', 125, y);
    doc.text('Priority Rating', 160, y);

    y += 8;
    doc.setFont('helvetica', 'normal');

    topics.slice(0, 12).forEach((topic: any) => {
      if (y > 270) return; // Prevent page overflow
      doc.text(String(topic.name || 'Unnamed Topic').slice(0, 35), 18, y);
      doc.text(`${Number(topic.financialImpact || 0).toFixed(1)} / 5.0`, 90, y);
      doc.text(`${Number(topic.impactMateriality || 0).toFixed(1)} / 5.0`, 125, y);
      doc.text(String(topic.isMaterial ? 'HIGH MATERIAL' : 'MONITOR'), 160, y);
      y += 7;
    });

    // Footer Stamp
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text('Official Cryptographic Certificate generated by ESG GO OmniAgent Swarm Engine v2.9.0', 15, 285);

    const pdfArrayBuffer = doc.output('arraybuffer');

    return new Response(pdfArrayBuffer, {
      status: 200,
      headers: {
        'Content-Type': 'application/pdf',
        'Content-Disposition': `attachment; filename="5T_Materiality_Certificate_${record.id.slice(0, 8)}.pdf"`,
      },
    });
  } catch (error) {
    console.error('[materiality/export-pdf]', error);
    return NextResponse.json(
      { success: false, error: (error as Error).message },
      { status: 500 }
    );
  }
}
